        cells = row.cells
        
        # col[1]: 教學目標
        set_cell(cells[1], objective)
        # col[4]: 起迄日期
        set_cell(cells[4], date_range)
        # col[5]: 教學方法
        set_cell(cells[5], methods)
        # col[6]: 評量方式
        set_cell(cells[6], assessments)
        # col[8]: 主動學習
