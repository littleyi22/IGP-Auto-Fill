        # col[9]: 認知能力（spans 9+10）
        set_cell(cells[9], str(scores[1]))
        # col[11]: 作業表現
        set_cell(cells[11], str(scores[2]))
        # col[12]: 表達能力
        set_cell(cells[12], str(scores[3]))
        # col[13]: 同儕合作
        set_cell(cells[13], str(scores[4]))
        # col[14]: 傾聽態度
        set_cell(cells[14], str(scores[5]))
        # col[15]: 評量日期
        set_cell(cells[15], eval_date)
        
        print(f"  ✅ 填入第{i+1}週: {date_range}")

